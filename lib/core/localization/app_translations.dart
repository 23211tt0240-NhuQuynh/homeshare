    final targetLang = (lang != null && _translations.containsKey(lang)) ? lang : 'vi';
    final dict = _translations[targetLang] ?? _translations['vi']!;
    if (dict.containsKey(key)) {
      return dict[key]!;
    }
    // Fallback về Tiếng Việt nếu ngôn ngữ hiện tại thiếu từ
    final viDict = _translations['vi']!;
    return viDict[key] ?? key;
  }
